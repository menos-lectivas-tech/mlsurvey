<?php
/**
 * Regenerates the certification authorities trusted for the certificate that
 * signs the declaration, from the Spanish trusted list (TSL) of qualified trust
 * service providers, the one the EU list of trusted lists points to:
 *
 * - certs/declaracion_ca.pem: the certificates of the services of type CA/QC
 *   with status "granted" and for electronic signatures (ForeSignatures) that
 *   are in force. They are the trust anchors, even the intermediate ones: no
 *   other CA under the same root (components, seals, web servers) is trusted.
 * - certs/declaracion_intermediates.pem: intermediate CAs needed when the TSL
 *   lists only the root, as the DNIe (AC RAIZ DNIE 2 → AC DNIE 004...), which
 *   are not always in the signature. They aren't trusted: they are only kept if
 *   they are issued by one of the anchors, and they are checked again on every
 *   signature.
 *
 * Usage: php updatecas.php [TSL URL]
 * Review the changes (git diff certs/) before committing them.
 */
if (PHP_SAPI !== "cli")
    exit (1);

const TSL_URL = "https://tsl.digital.gob.es/TSL.xml";
const TSL_NS = "http://uri.etsi.org/02231/v2#";
const CA_FILE = __DIR__ . "/certs/declaracion_ca.pem";
const INTERMEDIATES_FILE = __DIR__ . "/certs/declaracion_intermediates.pem";
/* Intermedias de las CA que la TSL lista solo por su raíz. Se descargan por
   http: no hace falta más, porque se comprueba que las firme la raíz. */
const INTERMEDIATE_URLS = [
    "http://pki.policia.es/dnie/certs/AC004.crt",
    "http://pki.policia.es/dnie/certs/AC005.crt",
    "http://pki.policia.es/dnie/certs/AC006.crt",
];

function fail (string $msg){
    fwrite (STDERR, "{$msg}\n");
    exit (1);
}

function download (string $url): string {
    /* https con la verificación por defecto de PHP (CA del sistema). */
    $ctx = stream_context_create (["http" => ["timeout" => 60, "follow_location" => 1]]);
    $data = @file_get_contents ($url, false, $ctx);
    if ($data === false || $data === "")
        fail ("Can't download {$url}");
    return $data;
}

function toPem (string $data): ?string {
    if (!str_contains ($data, "-----BEGIN CERTIFICATE-----"))
        $data = "-----BEGIN CERTIFICATE-----\n" . chunk_split (base64_encode ($data), 64, "\n") .
            "-----END CERTIFICATE-----\n";
    $cert = @openssl_x509_read ($data);
    return $cert !== false && openssl_x509_export ($cert, $pem) ? $pem : null;
}

function subjectLine (array $info): string {
    $parts = [];
    foreach ($info["subject"] as $k => $v)
        $parts[] = $k . "=" . implode (",", (array) $v);
    return implode (", ", $parts);
}

function inForce (array $info): bool {
    return $info["validFrom_time_t"] <= time () && $info["validTo_time_t"] > time ();
}

$url = $argv[1] ?? TSL_URL;
$doc = new DOMDocument ();
if (!$doc->loadXML (download ($url), LIBXML_NONET))
    fail ("The TSL of {$url} isn't XML");
$xp = new DOMXPath ($doc);
$xp->registerNamespace ("t", TSL_NS);
$seq = $xp->evaluate ("string(/t:TrustServiceStatusList/t:SchemeInformation/t:TSLSequenceNumber)");
$next = $xp->evaluate ("string(/t:TrustServiceStatusList/t:SchemeInformation/t:NextUpdate/t:dateTime)");
$territory = $xp->evaluate ("string(/t:TrustServiceStatusList/t:SchemeInformation/t:SchemeTerritory)");
if ($territory !== "ES" || $seq === "" || strtotime ($next) < time ())
    fail ("Not a current Spanish TSL (territory {$territory}, sequence {$seq}, next update {$next})");

$anchors = [];
$query = "//t:TSPService/t:ServiceInformation[" .
    "t:ServiceTypeIdentifier='http://uri.etsi.org/TrstSvc/Svctype/CA/QC' and " .
    "t:ServiceStatus='http://uri.etsi.org/TrstSvc/TrustedList/Svcstatus/granted' and " .
    ".//t:AdditionalServiceInformation/t:URI='http://uri.etsi.org/TrstSvc/TrustedList/SvcInfoExt/ForeSignatures']";
foreach ($xp->query ($query) as $si){
    $tsp = $xp->evaluate ("string(ancestor::t:TrustServiceProvider/t:TSPInformation/t:TSPName/t:Name[1])", $si);
    $service = $xp->evaluate ("string(t:ServiceName/t:Name[1])", $si);
    foreach ($xp->query ("t:ServiceDigitalIdentity/t:DigitalId/t:X509Certificate", $si) as $node){
        $pem = toPem ((string) base64_decode (preg_replace ('/\s+/', '', $node->textContent), true));
        if ($pem === null)
            fail ("Bad certificate in the service {$service}");
        $info = openssl_x509_parse ($pem);
        if (!inForce ($info))
            continue;
        $anchors[openssl_x509_fingerprint ($pem, "sha256")] =
            "# {$tsp} | {$service}\n# " . subjectLine ($info) . "\n" . $pem;
    }
}
if (count ($anchors) < 10)
    fail ("Only " . count ($anchors) . " CAs found in the TSL: not writing them");
ksort ($anchors);

$header = "# Generated by updatecas.php from {$url}\n# TSL sequence number {$seq}, next update {$next}\n";
$tmpca = tempnam (sys_get_temp_dir (), "mlca");
file_put_contents ($tmpca, $header . implode ("\n", $anchors));

$intermediates = [];
foreach (INTERMEDIATE_URLS as $iurl){
    $pem = toPem (download ($iurl));
    if ($pem === null)
        fail ("{$iurl} isn't a certificate");
    $info = openssl_x509_parse ($pem);
    $certfile = tempnam (sys_get_temp_dir (), "mlca");
    file_put_contents ($certfile, $pem);
    exec ("openssl verify -no-CApath -no-CAstore -partial_chain -CAfile " . escapeshellarg ($tmpca) .
        " " . escapeshellarg ($certfile) . " 2>&1", $out, $code);
    unlink ($certfile);
    if ($code !== 0 || ($info["extensions"]["basicConstraints"] ?? "") === "" ||
            !str_contains ($info["extensions"]["basicConstraints"], "CA:TRUE"))
        fail ("{$iurl} isn't a CA issued by one of the TSL: " . implode (" ", $out));
    $intermediates[] = "# {$iurl}\n# " . subjectLine ($info) . "\n" . $pem;
}

rename ($tmpca, CA_FILE);
chmod (CA_FILE, 0644);
file_put_contents (INTERMEDIATES_FILE, "# Generated by updatecas.php. Not trusted: only used for " .
    "building the chain up to certs/declaracion_ca.pem\n" . implode ("\n", $intermediates));
echo count ($anchors) . " CAs written to " . CA_FILE . "\n";
echo count ($intermediates) . " intermediates written to " . INTERMEDIATES_FILE . "\n";
